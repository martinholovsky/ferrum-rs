#!/usr/bin/env python3
"""Writes docs/residual-cwes.md: every CWE that safe Rust can still contain under
Corten (writable in safe Rust and not a verified elimination), grouped by the
mitigation strategy in audit/residual/assignment.csv. Strategies are defined in
audit/residual/strategies.csv; the proposal behind them is
docs/residual-mitigation.md.

Refuses (exit 1) when the assignment and the residual set disagree: a residual
CWE with no strategy, an assigned CWE that is no longer residual, or a strategy
that is not defined. --check also refuses when the doc is stale.

Usage: scripts/residual-map.py [--check]   (run from the repository root)
"""

import collections
import csv
import sys
from pathlib import Path

TABLE = Path("audit/applicability/table.csv")
LEDGER = Path("ledger/cwe-ledger.csv")
STRATEGIES = Path("audit/residual/strategies.csv")
ASSIGNMENT = Path("audit/residual/assignment.csv")
DOC = Path("docs/residual-cwes.md")

# MITRE, 2025 CWE Top 25 (page last updated 2025-12-15) and 2025 Top 10 KEV
# Weaknesses (page last updated 2026-01-27), read 2026-11-01:
# https://cwe.mitre.org/top25/archive/2025/2025_cwe_top25.html
# https://cwe.mitre.org/top25/archive/2025/2025_kev_list.html
TOP25 = [79, 89, 352, 862, 787, 22, 416, 125, 78, 94, 120, 434, 476, 121, 502,
         122, 863, 20, 284, 200, 306, 918, 77, 639, 770]
KEV10 = [78, 416, 787, 306, 502, 22, 94, 288, 122, 79]
LEAF = {"Base", "Variant"}


def num(cwe_id):
    return int(cwe_id.split("-")[1])


def load():
    table = {r["cwe_id"]: r for r in csv.DictReader(TABLE.open(newline=""))}
    ledger = {r["cwe_id"]: r for r in csv.DictReader(LEDGER.open(newline=""))}
    strategies = {r["strategy"]: r for r in csv.DictReader(STRATEGIES.open(newline=""))}
    assignment = {r["cwe_id"]: r["strategy"] for r in csv.DictReader(ASSIGNMENT.open(newline=""))}
    return table, ledger, strategies, assignment


def residual(table):
    return {i for i, r in table.items() if r["safe_rust"] == "yes"
            and not (r["ledger_bucket"] == "E" and r["ledger_status"] == "verified")}


def formula_cells(path):
    # CWE-1236, as corten-ledger checks the ledger: these files are edited by
    # hand and opened in spreadsheets, so no cell may start a formula.
    rows = list(csv.reader(path.open(newline="")))
    return [f"{path}:{n}: cell starts with {cell[0]!r}" for n, row in enumerate(rows, 1)
            for cell in row if cell[:1] in ("=", "+", "-", "@", "\t", "\r")]


def problems(res, strategies, assignment):
    out = formula_cells(STRATEGIES) + formula_cells(ASSIGNMENT)
    out += [f"{i}: residual but has no strategy" for i in sorted(res - assignment.keys(), key=num)]
    out += [f"{i}: assigned but not residual" for i in sorted(assignment.keys() - res, key=num)]
    out += [f"{i}: unknown strategy {s!r}" for i, s in sorted(assignment.items(), key=lambda kv: num(kv[0]))
            if s not in strategies]
    return out


def render(table, ledger, strategies, assignment, res):
    by = collections.defaultdict(list)
    for i in sorted(res, key=num):
        by[assignment[i]].append(i)
    order = sorted(strategies.values(), key=lambda s: int(s["order"]))
    leaf = [i for i in res if ledger[i]["abstraction"] in LEAF]
    top = sorted((c for c in TOP25 if f"CWE-{c}" in res), key=TOP25.index)
    kev = sorted((c for c in KEV10 if f"CWE-{c}" in res), key=KEV10.index)
    bucket = collections.Counter(table[i]["ledger_bucket"] for i in res)

    def ids(nums):
        return ", ".join(f"CWE-{n}" for n in nums) or "none"

    lines = [
        "# CWEs that remain under Rust and Corten",
        "",
        "Generated by `scripts/residual-map.py` from `audit/applicability/table.csv`, `ledger/cwe-ledger.csv` and",
        "`audit/residual/`; do not edit by hand. The proposal for each strategy is",
        "[`residual-mitigation.md`](residual-mitigation.md).",
        "",
        f"**{len(res)} CWEs remain**: safe Rust can write them, and Corten has no verified elimination for them.",
        f"By ledger bucket: {bucket['E']} claimed eliminations (E, unverified), {bucket['C']} checkable (C),",
        f"{bucket['O']} out of reach (O). {len(leaf)} are Base or Variant weaknesses; the other",
        f"{len(res) - len(leaf)} are Pillars, Classes or Compounds that overlap their children.",
        "",
        f"Of MITRE's 2025 Top 25, {len(top)} remain: {ids(top)}.",
        f"Of the 2025 Top 10 KEV weaknesses, {len(kev)} remain: {ids(kev)}.",
        "",
        "Each CWE has one strategy, the one expected to reduce it most. The assignment is a first pass",
        "made from the category, the name and the review's reasoning, and is meant to be revised.",
        "",
        "| # | Strategy | Layer | Effect | CWEs | Base or Variant | Top 25 | KEV |",
        "| ---: | --- | --- | --- | ---: | ---: | --- | --- |",
    ]
    for s in order:
        mine = by.get(s["strategy"], [])
        t = [n for n in TOP25 if f"CWE-{n}" in mine]
        k = [n for n in KEV10 if f"CWE-{n}" in mine]
        lines.append(
            f"| {s['order']} | [{s['title']}](#{s['strategy']}) | {s['layer']} | {s['effect']} | {len(mine)} | "
            f"{sum(ledger[i]['abstraction'] in LEAF for i in mine)} | "
            f"{', '.join(map(str, t)) or '-'} | {', '.join(map(str, k)) or '-'} |"
        )
    lines.append(f"| | **Total** | | | **{len(res)}** | **{len(leaf)}** | **{len(top)}** | **{len(kev)}** |")
    for s in order:
        mine = by.get(s["strategy"], [])
        lines += [
            "",
            f'<a id="{s["strategy"]}"></a>',
            f"## {s['order']}. {s['title']} ({len(mine)})",
            "",
            f"Layer: {s['layer']}. Effect: {s['effect']}.",
            "",
            "| CWE | Name | Category | Abstraction | Bucket |",
            "| --- | --- | --- | --- | --- |",
        ]
        for i in mine:
            r = table[i]
            mark = " (Top 25)" if num(i) in TOP25 else ""
            mark += " (KEV)" if num(i) in KEV10 else ""
            b = r["ledger_bucket"] + (", claimed" if r["ledger_bucket"] == "E" else "")
            lines.append(
                f"| [{i}](https://cwe.mitre.org/data/definitions/{num(i)}.html){mark} | {r['name']} | "
                f"{r['category']} | {ledger[i]['abstraction']} | {b} |"
            )
    summary = (f"residual {len(res)} (E {bucket['E']} C {bucket['C']} O {bucket['O']}), base/variant {len(leaf)}, "
               f"top25 {len(top)}, kev {len(kev)}, strategies "
               + " ".join(f"{s['strategy']}={len(by.get(s['strategy'], []))}" for s in order))
    return "\n".join(lines) + "\n", summary


def main() -> int:
    table, ledger, strategies, assignment = load()
    res = residual(table)
    bad = problems(res, strategies, assignment)
    if bad:
        print("\n".join(bad), file=sys.stderr)
        print(f"residual map refused: {len(bad)} problems", file=sys.stderr)
        return 1
    doc, summary = render(table, ledger, strategies, assignment, res)
    if "--check" in sys.argv[1:]:
        if not DOC.exists() or DOC.read_text() != doc:
            print(f"{DOC} is stale: run scripts/residual-map.py", file=sys.stderr)
            return 1
    else:
        DOC.write_text(doc)
    print(summary)
    return 0


if __name__ == "__main__":
    sys.exit(main())
